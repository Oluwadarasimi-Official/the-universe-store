import Link from "next/link";
import { notFound } from "next/navigation";
import { requireRole, canEdit } from "@/lib/auth";
import { adminDb } from "@/lib/supabase/clients";
import { A } from "@/lib/admin";
import { Flash, Head, Status } from "@/components/admin/ui";
import { Submit, CopyButton, DownloadButton } from "@/components/admin/client";
import { draftAction } from "../../content-actions";
import { fmtDate } from "@/lib/util";

const List = ({ title, items, tone }: { title: string; items: string[]; tone?: string }) => (
  <section className={`notice ${tone || ""}`}><b className="small">{title}</b>{items?.length ? <ul className="small" style={{ paddingLeft: 18, margin: "6px 0 0" }}>{items.map((x, i) => <li key={i}>{typeof x === "string" ? x : JSON.stringify(x)}</li>)}</ul> : <p className="small" style={{ margin: "6px 0 0" }}>None listed.</p>}</section>
);

export default async function Draft({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<Record<string, string>> }) {
  const me = await requireRole(); const { id } = await params; const sp = await searchParams;
  if (!/^[0-9a-f-]{36}$/.test(id)) notFound();
  const { data: d } = await adminDb().from("content_drafts").select("*").eq("id", id).maybeSingle();
  if (!d) notFound();
  const { data: products } = d.product_ids?.length ? await adminDb().from("products").select("id,title").in("id", d.product_ids) : { data: [] as any[] };
  const edit = canEdit(me.role);
  const F = ({ to, label, cls = "btn btn-outline btn-sm", confirm }: { to: string; label: string; cls?: string; confirm?: string }) => <form action={draftAction}><input type="hidden" name="id" value={id} /><input type="hidden" name="to" value={to} /><Submit className={cls} confirm={confirm}>{label}</Submit></form>;
  return (
    <>
      <Head title={d.title || "Draft"} desc={`${d.format.replace(/_/g, " ")} · ${d.tone} · created ${fmtDate(d.created_at, true)}`}><Status s={d.status} /></Head>
      <Flash sp={sp} />
      <p className="small muted">Generated by <b>{d.ai_provider || "manual"}</b>{d.ai_model ? ` / ${d.ai_model}` : ""}.{d.fallback_reason ? ` Fallback occurred: ${d.fallback_reason}` : ""}</p>
      <div className="split">
        <div className="stack">
          <form action={draftAction} className="card card-pad">
            <input type="hidden" name="id" value={id} /><input type="hidden" name="to" value="save" />
            <div className="field"><label htmlFor="t">Title</label><input id="t" name="title" className="input" defaultValue={d.title || ""} disabled={!edit} /></div>
            <div className="field"><label htmlFor="b">Draft</label><textarea id="b" name="body" className="textarea" style={{ minHeight: 320 }} defaultValue={d.body} disabled={!edit} /></div>
            {edit && <Submit className="btn btn-primary btn-sm">Save edits</Submit>}
          </form>
          <div className="row"><CopyButton text={d.body} label="Copy text" /><DownloadButton text={`${d.title || ""}\n\n${d.body}`} filename={`draft-${id.slice(0, 8)}.txt`} /></div>
        </div>
        <div className="stack">
          <section className="card card-pad"><b className="small">Based on products</b>{products?.length ? <ul className="small" style={{ paddingLeft: 18 }}>{products.map((p: any) => <li key={p.id}><Link href={A(`/products/${p.id}`)}>{p.title}</Link></li>)}</ul> : <p className="small muted">No product records.</p>}</section>
          <List title="Source facts used" items={d.source_facts} />
          <List title="Needs human verification" items={d.needs_verification} tone="notice-warn" />
          <List title="Missing facts" items={d.missing_facts} />
          {edit && <div className="row">
            {d.status === "draft" && <F to="submit" label="Submit for review" cls="btn btn-primary btn-sm" />}
            {d.format === "guide_outline" || d.format === "product_description" ? <F to="to_guide" label="Turn into guide draft" /> : null}
            {d.status === "approved" && d.format === "product_description" && d.product_ids?.length === 1 && <F to="to_product_desc" label="Use as product description" confirm="Replace the product's full description with this approved draft?" />}
            {d.format === "social_caption" && <Link className="btn btn-outline btn-sm" href={A("/social")}>Create social posts →</Link>}
            <F to="archive" label="Archive" />
            <F to="delete" label="Delete" cls="btn btn-danger btn-sm" confirm="Delete this draft?" />
          </div>}
        </div>
      </div>
    </>
  );
}
